package store

import (
	"context"
	"database/sql"
	"errors"
	"fmt"
	"time"
)

// Media is a row of the media table: an uploaded image's storage location,
// metadata and optional alt text.
type Media struct {
	ID           string
	FileKey      string // storage-relative key/path (e.g. "2026/08/<id>.png")
	OriginalName string
	Mime         string
	Size         int64
	Width        *int // nil only if a row was ever written without decoding dimensions
	Height       *int
	Alt          string
	Storage      string // "local" or "s3"
	UploadedBy   string // user id; "" once the uploader is deleted (ON DELETE SET NULL)
	CreatedAt    time.Time
}

// NewMedia holds the fields CreateMedia writes. Unlike most other NewXxx
// structs in this package, ID is supplied by the caller instead of being
// generated by CreateMedia: the media service needs the id before the row
// exists, to build the storage key the file is saved under.
type NewMedia struct {
	ID           string
	FileKey      string
	OriginalName string
	Mime         string
	Size         int64
	Width        *int
	Height       *int
	Alt          string
	Storage      string
	UploadedBy   string
}

// CreateMedia inserts a media row and returns it as stored.
func CreateMedia(ctx context.Context, db DBTX, in NewMedia) (Media, error) {
	m := Media{
		ID:           in.ID,
		FileKey:      in.FileKey,
		OriginalName: in.OriginalName,
		Mime:         in.Mime,
		Size:         in.Size,
		Width:        in.Width,
		Height:       in.Height,
		Alt:          in.Alt,
		Storage:      in.Storage,
		UploadedBy:   in.UploadedBy,
		CreatedAt:    time.Now().UTC(),
	}

	_, err := db.ExecContext(ctx, `
		INSERT INTO media (
			id, file_key, original_name, mime, size, width, height, alt,
			storage, uploaded_by, created_at
		) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
		m.ID, m.FileKey, m.OriginalName, m.Mime, m.Size, nullInt(m.Width), nullInt(m.Height),
		m.Alt, m.Storage, nullString(m.UploadedBy), formatTime(m.CreatedAt),
	)
	if err != nil {
		return Media{}, fmt.Errorf("insert media: %w", err)
	}
	return m, nil
}

// GetMediaByID looks up a media row by id. Returns ErrNotFound if no such
// row exists.
func GetMediaByID(ctx context.Context, db DBTX, id string) (Media, error) {
	row := db.QueryRowContext(ctx, `
		SELECT id, file_key, original_name, mime, size, width, height, alt,
			storage, uploaded_by, created_at
		FROM media WHERE id = ?`, id)
	return scanMedia(row)
}

// ListMedia returns one page of media, newest first (created_at DESC, id
// DESC tiebreak so ordering stays stable when timestamps collide), limit/
// offset paginated and optionally filtered by a case-insensitive substring
// of original_name.
func ListMedia(ctx context.Context, db DBTX, search string, limit, offset int) ([]Media, error) {
	where, args := mediaFilterClause(search)
	query := `
		SELECT id, file_key, original_name, mime, size, width, height, alt,
			storage, uploaded_by, created_at
		FROM media` + where +
		` ORDER BY created_at DESC, id DESC LIMIT ? OFFSET ?`
	args = append(args, limit, offset)

	rows, err := db.QueryContext(ctx, query, args...)
	if err != nil {
		return nil, fmt.Errorf("query media: %w", err)
	}
	defer rows.Close()

	items := make([]Media, 0)
	for rows.Next() {
		m, err := scanMedia(rows)
		if err != nil {
			return nil, err
		}
		items = append(items, m)
	}
	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("iterate media: %w", err)
	}
	return items, nil
}

// CountMedia returns how many media rows match search (ignoring
// pagination), for list response metadata.
func CountMedia(ctx context.Context, db DBTX, search string) (int, error) {
	where, args := mediaFilterClause(search)
	var count int
	if err := db.QueryRowContext(ctx, `SELECT COUNT(*) FROM media`+where, args...).Scan(&count); err != nil {
		return 0, fmt.Errorf("count media: %w", err)
	}
	return count, nil
}

// mediaFilterClause builds the shared WHERE clause (and its args) for
// ListMedia and CountMedia, so both apply identical filtering.
func mediaFilterClause(search string) (string, []any) {
	if search == "" {
		return "", nil
	}
	// INSTR over lowercased text gives a case-insensitive substring match
	// without exposing LIKE wildcard metacharacters in the search term.
	return " WHERE INSTR(LOWER(original_name), LOWER(?)) > 0", []any{search}
}

// UpdateMediaAlt overwrites a media row's alt text. Returns ErrNotFound if
// no such row exists.
func UpdateMediaAlt(ctx context.Context, db DBTX, id, alt string) error {
	res, err := db.ExecContext(ctx, `UPDATE media SET alt = ? WHERE id = ?`, alt, id)
	if err != nil {
		return fmt.Errorf("update media alt: %w", err)
	}
	return requireRowsAffected(res)
}

// DeleteMedia removes a media row. Returns ErrNotFound if no such row
// exists. Callers (the media service) are responsible for checking
// MediaInUse and deleting the underlying stored file first/after as
// appropriate; this function only ever touches the media table.
func DeleteMedia(ctx context.Context, db DBTX, id string) error {
	res, err := db.ExecContext(ctx, `DELETE FROM media WHERE id = ?`, id)
	if err != nil {
		return fmt.Errorf("delete media: %w", err)
	}
	return requireRowsAffected(res)
}

// MediaInUse reports whether id is referenced by any post's cover_image or
// og_image column. The media service uses this to refuse deleting media
// still attached to a post (400 "media_in_use").
func MediaInUse(ctx context.Context, db DBTX, id string) (bool, error) {
	var exists bool
	err := db.QueryRowContext(ctx,
		`SELECT EXISTS(
			SELECT 1 FROM posts WHERE cover_image = ? OR og_image = ?
			UNION ALL
			SELECT 1 FROM post_templates WHERE cover_image = ? OR og_image = ?
		)`,
		id, id, id, id,
	).Scan(&exists)
	if err != nil {
		return false, fmt.Errorf("check media in use: %w", err)
	}
	return exists, nil
}

func scanMedia(row rowScanner) (Media, error) {
	var (
		m          Media
		width      sql.NullInt64
		height     sql.NullInt64
		uploadedBy sql.NullString
		createdAt  string
	)
	err := row.Scan(&m.ID, &m.FileKey, &m.OriginalName, &m.Mime, &m.Size, &width, &height,
		&m.Alt, &m.Storage, &uploadedBy, &createdAt,
	)
	if errors.Is(err, sql.ErrNoRows) {
		return Media{}, ErrNotFound
	}
	if err != nil {
		return Media{}, fmt.Errorf("scan media: %w", err)
	}

	if width.Valid {
		w := int(width.Int64)
		m.Width = &w
	}
	if height.Valid {
		h := int(height.Int64)
		m.Height = &h
	}
	m.UploadedBy = stringOrEmpty(uploadedBy)

	if m.CreatedAt, err = parseTime(createdAt); err != nil {
		return Media{}, err
	}
	return m, nil
}
